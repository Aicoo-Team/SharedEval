#!/usr/bin/env node
/**
 * Pure helpers + tiny CLI backing scripts/experiments/run-cell.sh.
 *
 * Kept as plain ESM JavaScript so the exact same file runs on the host
 * (launcher) and inside the runner image with no TypeScript loader. Only
 * dependency is the repo's own `yaml` package. Unit-tested by
 * tests/experiments/docker-config.test.ts.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { parse as parseYaml } from 'yaml';

export const CELL_PROXY_PORT_V1 = 8888;
export const CELL_PROVENANCE_API_VERSION_V1 = 'sharedeval-cell-provenance/v1';
export const PROXY_CONFIG_FILE_V1 = 'tinyproxy.conf';
export const PROXY_ALLOWLIST_FILE_V1 = 'allowlist';
export const PROXY_CONFIG_MOUNT_V1 = '/etc/sharedeval-proxy';

const LOOPBACK_HOSTNAMES = new Set(['localhost', '127.0.0.1', '::1', '[::1]']);
// Plain DNS hostnames (or IPv4 literals) only: no fnmatch metacharacters can
// survive this, so the generated tinyproxy allowlist is always an exact match.
const HOSTNAME_PATTERN =
  /^[a-z0-9]([a-z0-9-]{0,62}[a-z0-9])?(\.[a-z0-9]([a-z0-9-]{0,62}[a-z0-9])?)*$/;
const IMAGE_ID_PATTERN = /^sha256:[a-f0-9]{64}$/;
const SHA256_HEX_PATTERN = /^[a-f0-9]{64}$/;

function fail(message) {
  throw new Error(`run-cell: ${message}`);
}

/**
 * Derives the single allowed egress host for a cell from the run config's
 * own model endpoint (never hand-written), plus the pieces of the config the
 * launcher needs before it starts any container. Full schema validation stays
 * with the production CLI's --check inside the container; this helper only
 * fails closed on endpoints the sandbox cannot support.
 */
export function deriveCellEndpointV1(configSource) {
  if (typeof configSource !== 'string' || configSource.length === 0) {
    fail('config source must be a non-empty string');
  }
  let config;
  try {
    config = parseYaml(configSource, { maxAliasCount: 0, uniqueKeys: true, strict: true });
  } catch {
    fail('config is not valid YAML');
  }
  if (!config || typeof config !== 'object' || Array.isArray(config)) {
    fail('config must be a YAML mapping');
  }
  const mode = config.workflow?.mode;
  if (mode !== 'multi' && mode !== 'single') {
    fail('config workflow.mode must be multi or single');
  }
  const model = config.model;
  if (!model || typeof model !== 'object' || Array.isArray(model)) {
    fail('config model block is missing');
  }
  if (model.provider !== 'openai-compatible' && model.provider !== 'azure-openai') {
    fail('config model.provider must be openai-compatible or azure-openai');
  }
  const rawUrl = model.provider === 'azure-openai' ? model.endpoint : model.baseUrl;
  if (typeof rawUrl !== 'string' || rawUrl.length === 0) {
    fail('config model endpoint URL is missing');
  }
  let url;
  try {
    url = new URL(rawUrl);
  } catch {
    fail('config model endpoint URL is invalid');
  }
  if (url.protocol === 'http:' && !LOOPBACK_HOSTNAMES.has(url.hostname)) {
    fail('plain HTTP model endpoints are refused for containerized cells; use https');
  }
  if (LOOPBACK_HOSTNAMES.has(url.hostname)) {
    fail('loopback model endpoints cannot be reached from inside the runner container');
  }
  if (url.protocol !== 'https:') {
    fail('config model endpoint must use https');
  }
  if (url.port !== '' && url.port !== '443') {
    fail('the model proxy allowlists exactly <host>:443; non-443 endpoints are refused');
  }
  const endpointHost = url.hostname;
  if (!HOSTNAME_PATTERN.test(endpointHost)) {
    fail('config model endpoint host is not a plain DNS hostname');
  }
  const outputDirectory = config.output?.directory ?? 'runs';
  if (typeof outputDirectory !== 'string' || outputDirectory.length === 0) {
    fail('config output.directory must be a non-empty string');
  }
  const segments = outputDirectory.split('/');
  if (
    outputDirectory.startsWith('/')
    || outputDirectory.includes('\\')
    || segments.some(segment => segment === '' || segment === '.' || segment === '..')
  ) {
    fail('config output.directory must be a safe relative path');
  }
  return Object.freeze({
    provider: model.provider,
    mode,
    endpointHost,
    endpointPort: 443,
    outputDirectory,
  });
}

export function tinyproxyAllowlistV1(endpointHost) {
  if (typeof endpointHost !== 'string' || !HOSTNAME_PATTERN.test(endpointHost)) {
    fail('proxy allowlist host is invalid');
  }
  return `${endpointHost}\n`;
}

export function tinyproxyConfigV1(options = {}) {
  const port = options.port ?? CELL_PROXY_PORT_V1;
  if (!Number.isInteger(port) || port < 1024 || port > 65535) {
    fail('proxy port is invalid');
  }
  return [
    '# Generated by scripts/experiments/run-cell.sh for one experiment cell.',
    '# CONNECT-only forward proxy; exactly one upstream host is allowlisted.',
    `Port ${port}`,
    'Listen 0.0.0.0',
    'Timeout 600',
    'MaxClients 16',
    'LogLevel Connect',
    'User nobody',
    'Group nobody',
    'DisableViaHeader Yes',
    '# Reachable only from the compose-internal network; never published to the host.',
    'Allow 0.0.0.0/0',
    '# CONNECT may target port 443 only.',
    'ConnectPort 443',
    '# Exact-hostname allowlist; every other destination is rejected.',
    `Filter "${PROXY_CONFIG_MOUNT_V1}/${PROXY_ALLOWLIST_FILE_V1}"`,
    'FilterType fnmatch',
    'FilterDefaultDeny Yes',
    '',
  ].join('\n');
}

export function writeProxyConfigV1(directory, endpointHost) {
  if (typeof directory !== 'string' || directory.length === 0) {
    fail('proxy config directory is required');
  }
  const allowlist = tinyproxyAllowlistV1(endpointHost);
  writeFileSync(path.join(directory, PROXY_CONFIG_FILE_V1), tinyproxyConfigV1(), { flag: 'wx' });
  writeFileSync(path.join(directory, PROXY_ALLOWLIST_FILE_V1), allowlist, { flag: 'wx' });
}

/**
 * Cell execution provenance written next to the run artifacts. The
 * `egressProbe` block mirrors experimentEgressProbeV1Schema
 * (src/experiments/v1/contracts.ts) so the scheduler can lift it verbatim.
 */
export function buildCellProvenanceV1(input) {
  if (!input || typeof input !== 'object') fail('provenance input is required');
  const {
    runId,
    imageRef,
    imageId,
    allowlistedEgress,
    configDigest = null,
    probe = null,
    probeExitCode,
    cliExitCode = null,
    runRoot,
    startedAt,
    finishedAt,
  } = input;
  for (const [name, value] of Object.entries({ runId, imageRef, runRoot, startedAt, finishedAt })) {
    if (typeof value !== 'string' || value.length === 0) fail(`provenance ${name} is required`);
  }
  if (typeof imageId !== 'string' || !IMAGE_ID_PATTERN.test(imageId)) {
    fail('provenance imageId must be a sha256 OCI image digest');
  }
  if (
    !Array.isArray(allowlistedEgress)
    || allowlistedEgress.length === 0
    || !allowlistedEgress.every(entry => typeof entry === 'string' && /^[a-z0-9.-]+:443$/.test(entry))
  ) {
    fail('provenance allowlistedEgress must list at least one host:443 entry');
  }
  if (configDigest !== null && !SHA256_HEX_PATTERN.test(configDigest)) {
    fail('provenance configDigest must be a sha256 hex digest');
  }
  if (!Number.isInteger(probeExitCode)) fail('provenance probeExitCode must be an integer');
  if (cliExitCode !== null && !Number.isInteger(cliExitCode)) {
    fail('provenance cliExitCode must be an integer when present');
  }
  const egressProbe = probe && typeof probe === 'object'
    ? {
      directEgressBlocked: probe.directEgressBlocked === true,
      nonAllowlistedEgressBlocked: probe.nonAllowlistedEgressBlocked === true,
      modelEndpointReachable: probe.modelEndpointReachable === true,
    }
    : null;
  return Object.freeze({
    apiVersion: CELL_PROVENANCE_API_VERSION_V1,
    runId,
    imageRef,
    imageDigest: imageId,
    allowlistedEgress: [...allowlistedEgress],
    proxyPort: CELL_PROXY_PORT_V1,
    configDigest,
    egressProbe,
    egressProbeReport: probe,
    egressProbeExitCode: probeExitCode,
    // null cliExitCode means the cell was refused before any model spend.
    cliExitCode,
    runRoot,
    startedAt,
    finishedAt,
  });
}

function parseFlags(argv) {
  const flags = new Map();
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (!argument.startsWith('--')) fail(`unexpected argument ${argument}`);
    const name = argument.slice(2);
    const value = argv[index + 1];
    if (value === undefined) fail(`--${name} requires a value`);
    index += 1;
    const existing = flags.get(name);
    if (existing === undefined) flags.set(name, [value]);
    else existing.push(value);
  }
  return flags;
}

function singleFlag(flags, name, { required = false } = {}) {
  const values = flags.get(name);
  if (!values) {
    if (required) fail(`--${name} is required`);
    return undefined;
  }
  if (values.length !== 1) fail(`--${name} may be given only once`);
  return values[0];
}

function mainV1(argv) {
  const [command, ...rest] = argv;
  if (command === 'derive-endpoint') {
    const [configPath, ...extra] = rest;
    if (!configPath || extra.length > 0) fail('usage: derive-endpoint <config.yaml>');
    let source;
    try {
      source = readFileSync(configPath, 'utf8');
    } catch {
      fail(`unable to read config ${configPath}`);
    }
    process.stdout.write(`${JSON.stringify(deriveCellEndpointV1(source))}\n`);
    return 0;
  }
  if (command === 'write-proxy-config') {
    const [directory, endpointHost, ...extra] = rest;
    if (!directory || !endpointHost || extra.length > 0) {
      fail('usage: write-proxy-config <directory> <endpoint-host>');
    }
    writeProxyConfigV1(directory, endpointHost);
    return 0;
  }
  if (command === 'write-provenance') {
    const flags = parseFlags(rest);
    const out = singleFlag(flags, 'out', { required: true });
    const probeFile = singleFlag(flags, 'probe-file');
    let probe = null;
    if (probeFile !== undefined) {
      try {
        probe = JSON.parse(readFileSync(probeFile, 'utf8'));
      } catch {
        probe = null;
      }
    }
    const cliExitCodeRaw = singleFlag(flags, 'cli-exit-code');
    const provenance = buildCellProvenanceV1({
      runId: singleFlag(flags, 'run-id', { required: true }),
      imageRef: singleFlag(flags, 'image-ref', { required: true }),
      imageId: singleFlag(flags, 'image-id', { required: true }),
      allowlistedEgress: flags.get('allowlisted') ?? [],
      configDigest: singleFlag(flags, 'config-digest') ?? null,
      probe,
      probeExitCode: Number(singleFlag(flags, 'probe-exit-code', { required: true })),
      cliExitCode: cliExitCodeRaw === undefined ? null : Number(cliExitCodeRaw),
      runRoot: singleFlag(flags, 'run-root', { required: true }),
      startedAt: singleFlag(flags, 'started-at', { required: true }),
      finishedAt: singleFlag(flags, 'finished-at', { required: true }),
    });
    // wx: cell provenance is written exactly once and never overwritten.
    writeFileSync(out, `${JSON.stringify(provenance, null, 2)}\n`, { flag: 'wx' });
    return 0;
  }
  fail(`unknown command ${command ?? '(none)'}`);
}

if (process.argv[1] && pathToFileURL(process.argv[1]).href === import.meta.url) {
  try {
    process.exitCode = mainV1(process.argv.slice(2));
  } catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
  }
}
